export function estimateFlightProgress(
  scheduledDeparture: string | null,
  scheduledArrival: string | null,
  actualDeparture: string | null
): number {
  const now = Date.now()
  const dep = actualDeparture
    ? new Date(actualDeparture).getTime()
    : scheduledDeparture
      ? new Date(scheduledDeparture).getTime()
      : now - 3600000
  const arr = scheduledArrival
    ? new Date(scheduledArrival).getTime()
    : dep + 7200000

  if (now >= arr) return 0.95

  // For "active" flights: if departure appears to be in the future (data lag),
  // assume the flight is roughly 40% through its route
  if (now <= dep) return 0.4

  return (now - dep) / (arr - dep)
}
